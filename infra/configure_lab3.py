"""Add local Lab 3 credentials to the existing environment file."""

import re
import secrets
from pathlib import Path


def main():
    path = Path(__file__).resolve().parents[1] / ".env"
    content = path.read_text(encoding="utf-8")
    existing = {line.partition("=")[0] for line in content.splitlines()}
    names = (
        "SUPERSET_DB_PASSWORD",
        "SUPERSET_SECRET_KEY",
        "SUPERSET_ADMIN_PASSWORD",
        "ANALYTICS_READER_PASSWORD",
        "OPENMETADATA_DB_PASSWORD",
        "OPENMETADATA_ADMIN_PASSWORD",
    )
    additions = [
        f"{name}={'aS9!' if name == 'OPENMETADATA_ADMIN_PASSWORD' else ''}{secrets.token_hex(24)}"
        for name in names
        if name not in existing
    ]
    # Upgrade only the 48-hex initial credential generated by this script.
    updated = re.sub(
        r"(?m)^(OPENMETADATA_ADMIN_PASSWORD=)([0-9a-f]{48})$", r"\1aS9!\2", content
    )
    if updated != content:
        path.write_text(updated, encoding="utf-8")
    if "OPENMETADATA_FERNET_KEY" not in existing:
        import base64

        additions.append(
            "OPENMETADATA_FERNET_KEY="
            + base64.urlsafe_b64encode(secrets.token_bytes(32)).decode()
        )
    if additions:
        with path.open("a", encoding="utf-8") as handle:
            handle.write("\n# Lab 3\n" + "\n".join(additions) + "\n")
    print(f"Lab 3 environment ready. Added {len(additions)} values.")


if __name__ == "__main__":
    main()
